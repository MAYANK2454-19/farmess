function normalise(value: string): string {
  return value
    .toLowerCase()
    .replace(/\s+district$/, "")
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

/** Resolve a provider's state name to the canonical list, or null if unknown. */
export function canonicalState(value: string | null | undefined): string | null {
  if (!value) return null;
  const lower = value.trim().toLowerCase();
  if (STATE_ALIASES[lower]) return STATE_ALIASES[lower];
  const key = normalise(value);
  if (STATE_ALIASES[key]) return STATE_ALIASES[key];
  return INDIA_STATES.find((state) => normalise(state) === key) ?? null;
}

/**
 * Resolve a provider's district name within a state. Returns the canonical
 * spelling when it matches the list, otherwise the provider's own cleaned name
 * (new or renamed districts are kept, not rejected).
 */
export function canonicalDistrict(state: string, value: string | null | undefined): string | null {
  if (!value) return null;
  const districts = INDIA_DISTRICTS[state] ?? [];
  const key = normalise(value);
  const match = districts.find((district) => normalise(district) === key);
  if (match) return match;
  const cleaned = value.replace(/\s+district$/i, "").trim();
  return cleaned || null;
}

export function districtsForState(state: string): readonly string[] {
  return INDIA_DISTRICTS[state] ?? [];
}

/** Indian PIN codes are six digits and never start with 0 (first digit 1–9). */
export function isValidPincode(value: string): boolean {
  return /^[1-9][0-9]{5}$/.test(value);
}

/** Round to about 1 km so stored locations are approximate, never a home address. */
export function approximateCoordinate(value: number): number {
  return Math.round(value * 100) / 100;
}

