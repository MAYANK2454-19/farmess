const key = (value: string) => value.toLowerCase().replace(/[^a-z0-9]+/g, "");

const BY_KEY = new Map<string, string>(COMMODITY_NAMES.map((name) => [key(name), name]));
const BY_ALIAS = new Map<string, string>(
  Object.entries(ALIASES).map(([alias, name]) => [key(alias), name]),
);
/** "Amla(Nelli Kai)" can be found by "amla": the part before the first bracket, when unique. */
const BY_BASE = (() => {
  const seen = new Map<string, string | null>();
  for (const name of COMMODITY_NAMES) {
    const base = key(name.split("(")[0]);
    if (!base || base === key(name)) continue;
    seen.set(base, seen.has(base) ? null : name);
  }
  return seen;
})();

function lookup(k: string): string | null {
  return BY_KEY.get(k) ?? BY_ALIAS.get(k) ?? BY_BASE.get(k) ?? null;
}

export type CanonicalCommodity = {
  /** The source's spelling when known, otherwise the cleaned input. */
  name: string;
  /** True when the name is one the source is known to use. */
  known: boolean;
};

/** Match what someone typed ("tomatoes", "bhindi", "PADDY") to the source's commodity name. */
export function canonicalCommodity(input: string | null | undefined): CanonicalCommodity {
  const cleaned = (input ?? "").replace(/\s+/g, " ").trim().slice(0, 100);
  if (!cleaned) return { name: "", known: false };
  const k = key(cleaned);
  const candidates = [k];
  if (k.endsWith("ies")) candidates.push(`${k.slice(0, -3)}y`);
  if (k.endsWith("oes")) candidates.push(k.slice(0, -2));
  if (k.endsWith("s")) candidates.push(k.slice(0, -1));
  for (const candidate of candidates) {
    const match = lookup(candidate);
    if (match) return { name: match, known: true };
  }
  return { name: cleaned, known: false };
}
